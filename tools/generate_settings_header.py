"""Generate the Seeed settings schema from the Python source of truth."""
from pathlib import Path
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from display_settings import DEVICE_SPECS


def header():
    lines = ['#pragma once', '// Generated by tools/generate_settings_header.py; do not edit.',
             '#include <stdint.h>', 'struct DeviceSettings {']
    lines += [f'    int32_t {name} = {int(default)};' for name, _, default, *_ in DEVICE_SPECS]
    lines += ['};', 'struct SettingSpec { const char *key; int32_t DeviceSettings::*member; int32_t low, high; };',
              'static const SettingSpec SETTING_SPECS[] = {']
    lines += [f'    {{"{wire}", &DeviceSettings::{name}, {low}, {high}}},' for name, wire, _, low, high in DEVICE_SPECS]
    lines += ['};', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    path = ROOT / 'firmware/seeed_trmnl/settings_schema.h'
    if '--check' in sys.argv:
        if path.read_text() != header(): raise SystemExit('Generated settings header is stale')
    else:
        path.write_text(header(), encoding='utf-8')
